#!/usr/bin/env python3
"""Generated docs for pi-foreman (stdlib, 3.13+).

    python scripts/foreman_docs.py features [--check]
        Write docs/features.md from config/features.json, the L1 defaults and the layer
        rules in foreman_config.py. --check writes nothing, prints a diff and exits 1 on drift.
    python scripts/foreman_docs.py dormant --config-json <path|->
        Print the ids of features whose switch is not satisfied by that config (a merged
        config object, or the `merged --json` result that holds it under "config").

The shared enumerators (schema leaves, registered commands, `/foreman` and `bin/foreman`
subcommands) live here; tests/test_docs.py imports them.
"""
from __future__ import annotations

import argparse
import difflib
import inspect
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import foreman_config as fc  # noqa: E402

ROOT = HERE.parent
FEATURES_PATH = ROOT / "config" / "features.json"
OUT_PATH = ROOT / "docs" / "features.md"
PLACEHOLDER = "<x>"
BEGIN = "<!-- BEGIN GENERATED: foreman_docs.py features -->"
END = "<!-- END GENERATED -->"

HEADER = """# Features overview

> If you are an agent setting pi-foreman up, read this file fully: it lists every feature, its state on a fresh install, its keys with defaults and layer rules, and how to switch it on.
> Generated by `scripts/foreman_docs.py features` from `config/features.json`, `config/foreman.defaults.json` and the layer rules in `scripts/foreman_config.py`; do not edit it by hand.
> Regenerate with `python scripts/foreman_docs.py features` (or run the tests with `FOREMAN_DOCS_UPDATE=1`); each feature links the area doc that holds the details.
"""


def read(p):
    return Path(p).read_text(encoding="utf-8")


# ---------------------------------------------------------------- enumerators

def schema_leaves(node, path=()):
    """Leaf key paths of the schema. A map (additionalProperties object schema) adds a
    PLACEHOLDER segment; a node with no `properties` and no object-valued
    additionalProperties with properties is a leaf."""
    props = node.get("properties", {})
    out = []
    for k, v in props.items():
        out += schema_leaves(v, path + (k,))
    ap = node.get("additionalProperties")
    if isinstance(ap, dict) and (ap.get("properties") or ap.get("additionalProperties")):
        out += schema_leaves(ap, path + (PLACEHOLDER,))
    if not props and path and not out:
        out.append(path)
    return out


def command_names(root=ROOT):
    names = set()
    for p in sorted((Path(root) / "extensions").rglob("*.ts")):
        if "node_modules" in p.parts or "test" in p.parts:
            continue
        names.update(re.findall(r'pi\.registerCommand\(\s*"([^"]+)"', read(p)))
    return names


def foreman_subcommands(root=ROOT):
    src = read(Path(root) / "extensions" / "core-adapter" / "index.ts")
    start = src.index('pi.registerCommand("foreman"')
    end = src.index("async function doctor", start)
    return set(re.findall(r'\bsub (?:===|!==) "([a-z][a-z-]*)"', src[start:end]))


def bin_subcommands(root=ROOT):
    """`case` arms of bin/foreman plus the subcommands it handles with `if [ "$sub" = ... ]`."""
    src = read(Path(root) / "bin" / "foreman")
    names = set(re.findall(r"^\s+([a-z][a-z-]*)\)\s+script=", src, re.M))
    names.update(re.findall(r'^\s*(?:el)?if \[ "\$sub" = "([a-z][a-z-]*)" \]', src, re.M))
    return names


def enumerated_commands(root=ROOT):
    """Every command a user can type, in the spelling the docs use."""
    out = {"/" + c for c in command_names(root)}
    out |= {"/foreman " + s for s in foreman_subcommands(root)}
    out |= {"foreman " + b for b in bin_subcommands(root)}
    return out


# ---------------------------------------------------------------- map helpers

def load_features(path=FEATURES_PATH):
    return json.loads(read(path))


def load_defaults():
    return json.loads(read(fc.DEFAULTS_PATH))


def load_leaves():
    return [tuple(p) for p in schema_leaves(json.loads(read(fc.SCHEMA_PATH)))]


def split(pattern):
    return tuple(pattern.split("."))


def pattern_matches(pattern, leaf):
    """A key pattern covers a leaf when it is a segment prefix of it; `*` matches one segment,
    `<x>` only the schema's map placeholder."""
    pat = split(pattern) if isinstance(pattern, str) else pattern
    if len(pat) > len(leaf):
        return False
    return all(p == "*" or p == s for p, s in zip(pat, leaf))


def feature_leaves(feature, leaves):
    return [l for l in leaves if any(pattern_matches(p, l) for p in feature["keys"])]


def lookup(cfg, keys):
    """Values at a dotted path; `*` fans out over a map. Missing paths yield nothing."""
    nodes = [cfg]
    for k in keys:
        nxt = []
        for n in nodes:
            if not isinstance(n, dict):
                continue
            if k == "*":
                nxt.extend(n.values())
            elif k in n:
                nxt.append(n[k])
        nodes = nxt
    return nodes


def predicate(on, value):
    if on == "true":
        return value is True
    if on == "nonempty":
        return isinstance(value, (list, dict, str)) and len(value) > 0
    if on == "nonnull":
        return value is not None
    raise ValueError("unknown switch predicate %r" % on)


def switch_on(feature, cfg):
    """None when the feature has no switch, else whether any value at the switch key satisfies it."""
    sw = feature.get("switch")
    if not sw:
        return None
    return any(predicate(sw["on"], v) for v in lookup(cfg, split(sw["key"])))


def expected_state(feature, cfg):
    """The state a switch implies on `cfg`: on, else off for a boolean switch, else opt-in."""
    sw = feature.get("switch")
    if not sw:
        return None
    if switch_on(feature, cfg):
        return "on"
    return "off" if sw["on"] == "true" else "opt-in"


def dormant(features, cfg):
    return [f["id"] for f in features["features"] if switch_on(f, cfg) is False]


# ---------------------------------------------------------------- layer rules

RULE_TEXT = {
    "false_only": "only false is accepted",
    "true_only": "only true is accepted",
    "union": "entries are added, never removed",
    "intersect": "can only narrow the list",
    "lower_only": "lower only",
    "lower_only_number": "lower only",
    "higher_only": "raise only",
    "higher_only_number": "raise only",
}
# Rules _restrict_ceremony applies in code without a constant table.
CEREMONY_RULES = {
    ("ceremony", "default"): "raise only: " + " < ".join(fc.TIERS),
    ("ceremony", "heavySignals"): RULE_TEXT["union"],
    ("ceremony", "scratchDir"): "narrow only: a subfolder of the earlier value",
}


def _keys_match(pattern, leaf, prefix=True):
    if len(pattern) > len(leaf) or (not prefix and len(pattern) != len(leaf)):
        return False
    return all(p == "*" or p == s for p, s in zip(pattern, leaf))


def _rule_text(rule, keys):
    if isinstance(rule, tuple) and rule[0] == "ordered":
        return "toward %s; tightest first: %s" % (rule[1][0], ", ".join(rule[1]))
    text = RULE_TEXT[rule]
    if rule.startswith("lower_only"):
        minimum = next((fc.LAYER_MINIMUM[k] for k in keys if k in fc.LAYER_MINIMUM), None)
        if minimum is not None:
            text += ", minimum %g" % minimum
        cap = next((fc.LAYER_CAP[k] for k in keys if k in fc.LAYER_CAP), None)
        if cap is not None:
            text += ", at most %g without an earlier value" % cap
    if rule.startswith("higher_only"):
        floor = next((fc.LAYER_FLOOR[k] for k in keys if k in fc.LAYER_FLOOR), None)
        if floor is not None:
            text += ", at least %g without an earlier value" % floor
    return text


def layer_rule(leaf):
    """What the project and session layers may do with this key, from foreman_config's tables."""
    if leaf[0] == "safety":
        rest = leaf[1:]
        if rest in fc.LOOSEN_ONLY:
            return "not in project/session (a loosening key)"
        for keys, rule in fc.TIGHTEN.items():
            if _keys_match(keys, rest):
                return "tighten-only (%s)" % _rule_text(rule, keys)
        return "not in project/session (no tighten rule for this safety key)"
    for keys, why in fc.IGNORED_KEYS:
        if _keys_match(keys, leaf):
            return "not in project/session (%s)" % why
    for keys, rule in fc.LAYER_TIGHTEN:
        if _keys_match(keys, leaf):
            return "tighten-only (%s)" % _rule_text(rule, keys)
    if leaf in CEREMONY_RULES:
        return "tighten-only (%s)" % CEREMONY_RULES[leaf]
    if leaf[0] == "roles" and len(leaf) == 3 and fc.ROLE_RULES.get(leaf[2]):
        return "tighten-only (%s)" % RULE_TEXT[fc.ROLE_RULES[leaf[2]]]
    if fc.CODEMODE_FALSE_ONLY and leaf[-1] == "codemode" and leaf[0] in ("roles", "providers"):
        return "tighten-only (%s)" % RULE_TEXT["false_only"]
    if fc.TRACE_DIR_IN_WORKSPACE and leaf == ("trace", "dir"):
        return "any layer (a project or session value must resolve inside the workspace)"
    return "any layer"


def layer_order():
    """Layer names in the order load_config merges them, read from its source."""
    src = inspect.getsource(fc.load_config)
    names = re.findall(r'(?:layers\.append\(|\[)\s*"(L\d|project|session)', src)
    seen = []
    for n in names:
        if n not in seen:
            seen.append(n)
    return seen


LAYER_TEXT = {
    "L1": ("package defaults", "`config/foreman.defaults.json`", "every key"),
    "L3": ("packages and overlays", "each installed package's `pi.foreman.config` (an organisation overlay), plus `--l3 PATH`", "every key"),
    "L2": ("user", "`<agent dir>/foreman.json` (`PI_CODING_AGENT_DIR`, default `~/.pi/agent`)", "every key"),
    "project": ("project", "`<repo>/.pi/foreman.json`, read only once Pi's project trust is resolved", "tighten-only keys only stricter, ignored keys dropped with a warning, no new role ids"),
    "session": ("session", "`--session-json` and launch flags, not persisted", "the project rules, and loosening keys are dropped"),
}


# ---------------------------------------------------------------- rendering

def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text):
    return "`%s`" % cell(text) if text else ""


def fmt_value(v):
    return json.dumps(v, ensure_ascii=False)


def default_text(leaf, defaults):
    if PLACEHOLDER not in leaf:
        vals = lookup(defaults, leaf)
        if not vals:
            return "unset"
        v = vals[0]
        if isinstance(v, dict) and v and all(isinstance(x, dict) for x in v.values()):
            return "keys: " + ", ".join(code(k) for k in v)
        return code(fmt_value(v))
    i = leaf.index(PLACEHOLDER)
    entries = []
    for parent in lookup(defaults, leaf[:i]):
        if not isinstance(parent, dict):
            continue
        for name, sub in parent.items():
            vals = lookup(sub, tuple("*" if s == PLACEHOLDER else s for s in leaf[i + 1:]))
            if vals:
                entries.append((name, vals[0]))
    if not entries:
        return "unset"
    parts = []
    for n, v in entries:
        part = "%s: %s" % (code(n), code(fmt_value(v)))
        if parts and sum(len(p) + 2 for p in parts) + len(part) > 240:
            parts.append("... (see `config/foreman.defaults.json`)")
            break
        parts.append(part)
    return ", ".join(parts)


def leaf_name(leaf):
    return ".".join(leaf)


def render(features=None, defaults=None, leaves=None):
    features = features if features is not None else load_features()
    defaults = defaults if defaults is not None else load_defaults()
    leaves = leaves if leaves is not None else load_leaves()
    fmap = {f["id"]: f for f in features["features"]}
    out = [HEADER, BEGIN, ""]

    out += ["## Install", "",
            "Verbatim from [install](install.md#install):", "", "```text"]
    out += features["install"]
    out += ["```", "",
            "Then map your models ([model-map](#model-map)), run `/foreman doctor` in Pi and check this inventory.",
            "Enable snippets below go into `<agent dir>/foreman.json` or an overlay's `pi.foreman.config`.", ""]

    out += ["## Layers", "",
            "Config merges in this order, later wins (maps deep-merge, leaves and lists are replaced):", ""]
    for n, name in enumerate(layer_order(), 1):
        label, where, may = LAYER_TEXT[name]
        out.append("%d. %s (`%s`): %s. May set: %s." % (n, label, name, where, may))
    out += ["",
            "The per-key layer rule in the tables below is read from `scripts/foreman_config.py` "
            "(`TIGHTEN`, `LOOSEN_ONLY`, `IGNORED_KEYS`, `LAYER_TIGHTEN`, `ROLE_RULES`, `CODEMODE_FALSE_ONLY`, "
            "`TRACE_DIR_IN_WORKSPACE`): `any layer`, `tighten-only (<rule>)` or `not in project/session (<reason>)`. "
            "A project or session value that would loosen a tighten-only key is dropped with a warning.", ""]

    out += ["## Feature inventory", "",
            "State is the fresh-install state with the package defaults: `on`, `off` (a switch you turn on) or "
            "`opt-in` (needs a value or a command from you).", "",
            "| Feature | State | Purpose | Enable | Doc |", "|---|---|---|---|---|"]
    for f in features["features"]:
        out.append("| [%s](#%s) | %s | %s | %s | [%s](%s) |" % (
            f["id"], f["id"], f["state"], cell(f["purpose"]),
            code(f["enable"]) if f["enable"] else "on by default",
            Path(f["doc"].split("#")[0]).stem, cell(f["doc"].replace("docs/", "", 1))))
    out.append("")

    out += ["## Feature keys", ""]
    for f in features["features"]:
        out += ["### %s" % f["id"], "", "**%s.** %s" % (f["title"], f["purpose"]), ""]
        sw = f.get("switch")
        if sw:
            out += ["Switch: `%s` is %s." % (sw["key"], {"true": "true", "nonempty": "non-empty",
                                                         "nonnull": "set"}[sw["on"]]), ""]
        own = feature_leaves(f, leaves)
        if own:
            out += ["| Key | Default | Layer |", "|---|---|---|"]
            for leaf in own:
                out.append("| %s | %s | %s |" % (code(leaf_name(leaf)), default_text(leaf, defaults),
                                                  cell(layer_rule(leaf))))
            out.append("")
        else:
            out += ["No config key.", ""]

    out += ["## Commands by feature", "", "| Feature | Commands |", "|---|---|"]
    for f in features["features"]:
        if f["commands"]:
            out.append("| [%s](#%s) | %s |" % (f["id"], f["id"], ", ".join(code(c) for c in f["commands"])))
    out.append("")

    out += ["## Overlay quick start", "",
            "What a private or organisation overlay usually sets, in this order (see [overlays](overlays.md)):", ""]
    for n, q in enumerate(features["overlayQuickStart"], 1):
        f = fmap[q["feature"]]
        line = "%d. [%s](#%s): %s" % (n, f["id"], f["id"], q["note"])
        if f["enable"] and f["enable"].startswith("{"):
            line += " Example: %s" % code(f["enable"])
        out.append(line)
    out.append("")

    out += ["## Invariants", "", "An overlay or a setup agent must not break these:", ""]
    out += ["- " + s for s in features["invariants"]]
    out += ["", "Keys the project and session layers may not set (`IGNORED_KEYS`; `*` = any entry):", "",
            "| Key | Reason |", "|---|---|"]
    for keys, why in fc.IGNORED_KEYS:
        out.append("| %s | %s |" % (code(".".join(keys)), cell(why)))
    for keys in fc.LOOSEN_ONLY:
        out.append("| %s | %s |" % (code("safety." + ".".join(keys)), "a loosening key (`LOOSEN_ONLY`)"))
    out += ["", END, ""]
    return "\n".join(out)


# ---------------------------------------------------------------- CLI

def cmd_features(args):
    text = render()
    current = read(OUT_PATH) if OUT_PATH.is_file() else ""
    if args.check:
        if current == text:
            return 0
        sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                   "docs/features.md", "generated"))
        print("docs/features.md is stale; run python scripts/foreman_docs.py features", file=sys.stderr)
        return 1
    if current != text:
        with open(str(OUT_PATH), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote %s" % OUT_PATH)
    else:
        print("up to date")
    return 0


def cmd_dormant(args):
    raw = sys.stdin.read() if args.config_json == "-" else read(args.config_json)
    cfg = json.loads(raw)
    if isinstance(cfg, dict) and isinstance(cfg.get("config"), dict) and "layers" in cfg:
        cfg = cfg["config"]
    for fid in dormant(load_features(), cfg):
        print(fid)
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(prog="foreman_docs")
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("features", help="write or check docs/features.md")
    s.add_argument("--check", action="store_true")
    s = sub.add_parser("dormant", help="print feature ids whose switch is off in a config")
    s.add_argument("--config-json", required=True, metavar="PATH|-")
    args = p.parse_args(argv)
    return cmd_features(args) if args.cmd == "features" else cmd_dormant(args)


if __name__ == "__main__":
    sys.exit(main())
