const fold = (platform: string) => (platform === "win32" || platform === "darwin" ? (s: string) => s.toLowerCase() : (s: string) => s);

export function sha256(bytes: Buffer): string {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

/**
 * Whether a line starts the appendix of a plan file (rulings, not the reviewed plan): a level 2 or 3 heading, case-insensitive,
 * whose text starts with Addendum, Addenda, Ruling, Rulings, Parent ruling or Decision log as a whole word (followed by the end of the
 * line, `:`, ` -`, ` –`, ` —`, ` (` or ` <digit>`), or the line `<!-- plan-appendix -->`. Trailing whitespace is ignored. The en and em dash also match as the
 * three latin1 chars of their UTF-8 bytes (E2 80 93/94; a real U+0080 control character is the bytes C2 80 and does not match), because planBody scans the bytes as latin1.
 */
export function isAppendixLine(line: string): boolean {
  const l = line.replace(/\s+$/, "");
  return l === "<!-- plan-appendix -->" || /^#{2,3}[ \t]+(?:addendum|addenda|rulings?|parent ruling|decision log)(?=$|:|[ \t](?:-|[\u2013\u2014])|[ \t]\(|[ \t]\d)/i.test(l) || bytesDash(l);
}

/** The keyword part matches case-insensitively, the latin1 dash bytes (E2 80 93/94) case-sensitively: C2 80 94 is no dash. */
function bytesDash(l: string): boolean {
  const m = /^#{2,3}[ \t]+(?:addendum|addenda|rulings?|parent ruling|decision log)[ \t]/i.exec(l);
  return m !== null && /^\u00e2\u0080[\u0093\u0094]/.test(l.slice(m[0].length));
}

/** Start offset of the first appendix line in `text`, or -1 (no appendix). `text` must keep one char per byte (latin1) when used for offsets. */
function appendixOffset(text: string): number {
  let at = 0;
  for (const line of text.split(/(?<=\n)/)) {
    if (isAppendixLine(line)) return at;
    at += line.length;
  }
  return -1;
}

/**
 * The plan body: the bytes before the first appendix line. With an appendix, trailing whitespace of the
 * body is normalised to one newline, so appending `\n## Ruling ...` to a file that ended in a newline keeps
 * the body (and so the version) unchanged. With no appendix the body is the whole file.
 */
export function planBody(bytes: Buffer): Buffer {
  const at = appendixOffset(bytes.toString("latin1"));
  if (at < 0) return bytes;
  return Buffer.from(bytes.subarray(0, at).toString("latin1").replace(/\s+$/, "") + "\n", "latin1");
}

/**
 * Version hash of a plan: sha256 of the body (planBody). Rulings, decision logs and addenda appended below
 * an appendix heading are outside review and approval; a body edit is a new version. Equals sha256(bytes)
 * when the file has no appendix.
 */
export function planVersionHash(bytes: Buffer): string {
  return sha256(planBody(bytes));
}

/** The version hash of a plan file by its name: an HTML page hashes whole, a markdown plan by its body above the appendix. */
export function planHash(name: string, bytes: Buffer): string {
  return name.endsWith(".html") ? sha256(bytes) : planVersionHash(bytes);
}

/** Escapes the lines of converted page text that isAppendixLine would take for an appendix start (a zero-width space after `## ` or `<!--`), so the copy's body ends exactly where the page ends. */
export function escapeAppendixLines(markdown: string): string {
  const ZWSP = String.fromCharCode(0x200b);
  return markdown.split("\n").map((l) => (isAppendixLine(l) ? (l.startsWith("<!--") ? l.replace("<!--", `<!--${ZWSP}`) : l.replace(/^#{2,3}[ \t]+/, (m) => `${m}${ZWSP}`)) : l)).join("\n");
}

function refused(why: string, scratchDir: string): { error: string } {
  return { error: `pi-foreman: ${CHECKPOINT_TOOL} refused: ${why}. Write the plan as ${scratchDir}/plan-<topic>.html (a page) or plan-<topic>.md (topic: letters, digits, . _ -, at most 64; a regular file, no symlink or hard link, at most 256 KiB) and call ${CHECKPOINT_TOOL} with that path.` };
}

export type FileRefusal = "missing" | "not_regular" | "hard_link" | "too_large" | "changed" | "unreadable";

/** Read `real` when it is a regular file with one link and at most `maxBytes` (checked before and after the open, no symlink followed). */
export function readRegularFile(real: string, maxBytes: number): { bytes: Buffer } | { refusal: FileRefusal } {
  let fd: number;
  try {
    const st = fs.lstatSync(real);
    if (!st.isFile()) return { refusal: "not_regular" };
    if (st.nlink !== 1) return { refusal: "hard_link" };
    if (st.size > maxBytes) return { refusal: "too_large" };
    fd = fs.openSync(real, fs.constants.O_RDONLY | (fs.constants.O_NOFOLLOW ?? 0));
  } catch {
    return { refusal: "missing" };
  }
  try {
    const st = fs.fstatSync(fd);
    if (!st.isFile() || st.nlink !== 1 || st.size > maxBytes) return { refusal: "changed" };
    const bytes = fs.readFileSync(fd);
    if (bytes.length > maxBytes) return { refusal: "too_large" };
    return { bytes };
  } catch {
    return { refusal: "unreadable" };
  } finally {
    fs.closeSync(fd);
  }
}

const PLAN_FILE_REFUSAL: Record<FileRefusal, string> = {
  missing: "the file does not exist or cannot be read",
  not_regular: "not a regular file",
  hard_link: "the file has more than one hard link",
  too_large: "the file is larger than 256 KiB",
  changed: "the file changed while it was read",
  unreadable: "the file cannot be read",
};

/** Validate a plan path and read the file; the record's hash comes from these bytes. */
export function readPlan(raw: unknown, o: PlanOpts): { plan: PlanFile } | { error: string } {
  const f = fold(o.platform);
  const abs = resolveToolPath(raw, o.cwd, o.home);
  if (!abs) return refused("path must be a non-empty string", o.scratchDir);
  const lexRoot = path.resolve(workspaceOf(o.cwd).root);
  const realRoot = realDeep(lexRoot);
  const root = [realRoot, lexRoot].find((r) => under(r, abs, o.platform));
  if (!root) return refused("the path is outside the workspace", o.scratchDir);
  // The same path below the real root: any symlink component makes its real path differ. The
  // components come from the case-preserved path; case folding only decided containment above.
  const depth = path.relative(f(root), f(abs)).split(path.sep).filter(Boolean).length;
  const candidate = path.join(realRoot, ...(depth ? path.resolve(abs).split(path.sep).slice(-depth) : []));
  const real = realDeep(candidate);
  if (f(real) !== f(candidate)) return refused("the path passes through a symlink", o.scratchDir);
  const scratch = scratchRoot(realRoot, o.scratchDir, o.platform);
  if (!scratch) return refused(`the scratch dir ${o.scratchDir} is disabled`, o.scratchDir);
  if (f(path.dirname(real)) !== f(scratch)) return refused(`the plan must be directly in ${o.scratchDir}`, o.scratchDir);
  const m = PLAN_NAME.exec(path.basename(real));
  if (!m) return refused("the file name must be plan-<topic>.md or plan-<topic>.html", o.scratchDir);
  // A page next to the copy's name (or the page itself) makes it an HTML plan whose path is the page's.
  const page = m[2] === "html" ? real : path.join(path.dirname(real), `plan-${m[1]}.html`);
  if (m[2] === "html" || exists(page)) return readHtmlPlan(m[1], page, realRoot, o);
  const file = readRegularFile(real, PLAN_MAX_BYTES);
  if ("refusal" in file) return refused(PLAN_FILE_REFUSAL[file.refusal], o.scratchDir);
  const rel = path.relative(realRoot, real).split(path.sep).join("/");
  return { plan: { topic: m[1], path: real, rel, bytes: file.bytes, hash: planVersionHash(file.bytes), kind: "md", markdown: file.bytes.toString("utf8") } };
}

const exists = (file: string): boolean => {
  try {
    fs.lstatSync(file);
    return true;
  } catch (e) {
    return (e as NodeJS.ErrnoException).code !== "ENOENT";
  }
};

const sleepSync = (ms: number): void => void Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
let tmpSeq = 0;

/** Exclusive temp file in the copy's folder, then a rename over it (a rename never follows a link at the target); one retry for the Windows sharing errors. Null, or why it failed. */
function writeCopy(copy: string, bytes: Buffer): string | null {
  const tmp = `${copy}.${process.pid}.${++tmpSeq}.tmp`;
  try {
    fs.writeFileSync(tmp, bytes, { flag: "wx" });
    try {
      fs.renameSync(tmp, copy);
    } catch (e) {
      const code = (e as NodeJS.ErrnoException).code;
      if (code !== "EPERM" && code !== "EBUSY") throw e;
      sleepSync(50);
      fs.renameSync(tmp, copy);
    }
    return null;
  } catch (e) {
    try {
      fs.rmSync(tmp, { force: true });
    } catch {
      // best effort
    }
    return `${path.basename(copy)} could not be written (${(e as NodeJS.ErrnoException).code ?? "error"})`;
  }
}

const twoFiles = (topic: string, why: string): string => `two plan files for ${topic}: plan-${topic}.html and a hand-written plan-${topic}.md (${why}); remove or rename one. plan-${topic}.md is not the generated copy (its first line lost the marker). The plan is plan-${topic}.html: delete plan-${topic}.md and the harness writes the copy again; delete plan-${topic}.html only to switch to a markdown plan`;

/** An HTML plan: the page is the source and the version; the markdown copy (marker, converted page, rulings) is derived from the same bytes and written when it differs. */
function readHtmlPlan(topic: string, page: string, realRoot: string, o: PlanOpts): { plan: PlanFile } | { error: string } {
  const file = readRegularFile(page, PLAN_MAX_BYTES);
  if ("refusal" in file) return refused(`${path.basename(page)}: ${PLAN_FILE_REFUSAL[file.refusal]}`, o.scratchDir);
  const dir = path.dirname(page);
  const rulingsFile = `rulings-${topic}.md`;
  const side = readRegularFile(path.join(dir, rulingsFile), PLAN_MAX_BYTES);
  if ("refusal" in side && side.refusal !== "missing") return refused(`${rulingsFile}: ${PLAN_FILE_REFUSAL[side.refusal]}`, o.scratchDir);
  const rulings = "bytes" in side ? side.bytes.toString("utf8") : "";
  let conv: ReturnType<typeof htmlToMarkdown>;
  try {
    conv = htmlToMarkdown(file.bytes.toString("utf8"));
  } catch (e) {
    return refused(`${path.basename(page)} could not be converted to markdown (${e instanceof Error ? e.message : "error"})`, o.scratchDir);
  }
  const appendix = rulings.trim() ? `\n<!-- plan-appendix -->\n${rulings}${rulings.endsWith("\n") ? "" : "\n"}` : "";
  const copy = `${generatedMarker(topic)}\n${escapeAppendixLines(conv.markdown)}${appendix}`;
  const copyBytes = Buffer.from(copy, "utf8");
  if (copyBytes.length > PLAN_MAX_BYTES) return refused("the generated copy (page text plus rulings) exceeds 256 KiB", o.scratchDir);
  const copyPath = path.join(dir, `plan-${topic}.md`);
  const cur = readRegularFile(copyPath, PLAN_MAX_BYTES);
  let copyError: string | undefined;
  if ("refusal" in cur && cur.refusal !== "missing") return refused(twoFiles(topic, PLAN_FILE_REFUSAL[cur.refusal]), o.scratchDir);
  if ("bytes" in cur) {
    if (cur.bytes.toString("utf8").split(/\r?\n/, 1)[0] !== generatedMarker(topic)) return refused(twoFiles(topic, "its first line is not the generated marker"), o.scratchDir);
    if (!cur.bytes.equals(copyBytes)) copyError = writeCopy(copyPath, copyBytes) ?? undefined;
  } else {
    copyError = writeCopy(copyPath, copyBytes) ?? undefined;
  }
  const rel = path.relative(realRoot, page).split(path.sep).join("/");
  return { plan: { topic, path: page, rel, bytes: file.bytes, hash: sha256(file.bytes), kind: "html", markdown: copy, copyPath, ...(copyError ? { copyError } : {}), title: conv.title, hidden: conv.hidden, rulings: rulings.trim() ? rulings : "" } };
}

/** Why the copy of an HTML plan on disk is not the current one (it differs from `plan.markdown`, or cannot be read), or null when it is current. */
export function copyStale(plan: PlanFile): string | null {
  if (plan.kind !== "html" || !plan.copyPath) return null;
  const cur = readRegularFile(plan.copyPath, PLAN_MAX_BYTES);
  if ("bytes" in cur && cur.bytes.equals(Buffer.from(plan.markdown, "utf8"))) return null;
  return plan.copyError ?? `${path.basename(plan.copyPath)} on disk is not the copy of the current page`;
}

/** Hash of the recorded plan file now, or null when it is gone or no longer passes the path rules. */
export function currentPlanHash(rec: PlanRecord, o: PlanOpts): string | null {
  const r = readPlan(rec.path, o);
  return "plan" in r ? r.plan.hash : null;
}

/** True when `raw` names a `plan-<topic>.md` or `.html` directly in the real scratch dir (file need not exist). */
export function isPlanPath(raw: unknown, o: PlanOpts): boolean {
  return scratchNamed(raw, o, PLAN_NAME) !== null;
}

/** The topic when `raw` names a `rulings-<topic>.md` (the rulings sidecar of an HTML plan) directly in the real scratch dir, else null. */
export function rulingsTopic(raw: unknown, o: PlanOpts): string | null {
  return scratchNamed(raw, o, RULINGS_NAME)?.[1] ?? null;
}

function scratchNamed(raw: unknown, o: PlanOpts, name: RegExp): RegExpExecArray | null {
  const abs = resolveToolPath(raw, o.cwd, o.home);
  if (!abs) return null;
  const realRoot = realDeep(path.resolve(workspaceOf(o.cwd).root));
  const scratch = scratchRoot(realRoot, o.scratchDir, o.platform);
  if (!scratch) return null;
  const real = realDeep(abs);
  return fold(o.platform)(path.dirname(real)) === fold(o.platform)(scratch) ? name.exec(path.basename(real)) : null;
}

/** The real `<handoff dir>/plan.md` when `raw` names it (the file need not exist), else null. A relative `raw` resolves against `o.cwd`. */
export function handoffPlanPath(raw: unknown, handoffDir: string | null | undefined, o: Pick<PlanOpts, "cwd" | "home" | "platform">): string | null {
  const dir = handoffDir?.trim();
  const abs = resolveToolPath(raw, o.cwd, o.home);
  if (!dir || !path.isAbsolute(dir) || !abs) return null;
  const f = fold(o.platform);
  const realDir = realDeep(path.resolve(dir));
  // Only the directory is resolved: a plan.md that is itself a symlink still matches by name, so the guarded read can refuse it and clear the path.
  const real = path.join(realDeep(path.dirname(abs)), path.basename(abs));
  return f(path.dirname(real)) === f(realDir) && path.basename(real) === HANDOFF_PLAN ? path.join(realDir, HANDOFF_PLAN) : null;
}

export const HANDOFF_PLAN = "plan.md";

/**
 * Guarded read of `<handoff dir>/plan.md` (a child session's plan): no symlink below the real handoff dir, a regular file with one hard link
 * of at most 256 KiB, opened with O_NOFOLLOW and checked again by fstat (same inode and size). A file that fails is not read.
 */
export function readHandoffPlan(handoffDir: string, platform: string): { plan: { path: string; bytes: Buffer; hash: string } } | { error: string } {
  const r = readHandoffFile(handoffDir, HANDOFF_PLAN, platform);
  return "error" in r ? r : { plan: { path: r.path, bytes: r.bytes, hash: planVersionHash(r.bytes) } };
}

export const HANDOFF_RESULT = "result.md";

/** The guarded read of `<handoff dir>/result.md` (a child session's result page): the same checks as readHandoffPlan. */
export function readHandoffResult(handoffDir: string, platform: string): { path: string; bytes: Buffer } | { error: string } {
  return readHandoffFile(handoffDir, HANDOFF_RESULT, platform);
}

/** The opened handle is the lstat'ed file: a regular single-link file of at most 256 KiB, same exact id and size; an unknown id fails. */
export function handoffStatsMatch(first: fs.BigIntStats, st: fs.BigIntStats): boolean {
  return st.isFile() && st.nlink === 1n && st.size <= BigInt(PLAN_MAX_BYTES) && sameFileId(st, first) && st.size === first.size;
}

function readHandoffFile(handoffDir: string, name: string, platform: string): { path: string; bytes: Buffer } | { error: string } {
  const f = fold(platform);
  if (!path.isAbsolute(handoffDir)) return { error: "the handoff dir is not absolute" };
  const candidate = path.join(realDeep(path.resolve(handoffDir)), name);
  if (f(realDeep(candidate)) !== f(candidate)) return { error: "the path passes through a symlink" };
  let fd: number;
  let first: fs.BigIntStats;
  try {
    first = fs.lstatSync(candidate, { bigint: true });
    if (!first.isFile()) return { error: "not a regular file" };
    if (first.nlink !== 1n) return { error: "the file has more than one hard link" };
    if (first.size > BigInt(PLAN_MAX_BYTES)) return { error: "the file is larger than 256 KiB" };
    fd = fs.openSync(candidate, fs.constants.O_RDONLY | (fs.constants.O_NOFOLLOW ?? 0));
  } catch {
    return { error: "the file does not exist or cannot be read" };
  }
  try {
    const st = fs.fstatSync(fd, { bigint: true });
    if (!handoffStatsMatch(first, st)) return { error: "the file changed while it was read" };
    const bytes = fs.readFileSync(fd);
    if (bytes.length > PLAN_MAX_BYTES) return { error: "the file is larger than 256 KiB" };
    return { path: candidate, bytes };
  } catch {
    return { error: "the file cannot be read" };
  } finally {
    fs.closeSync(fd);
  }
}

/** Why a builder launch is refused at this tier, or null. `currentHash` null = file gone or no longer valid. */
export function builderLaunchRefusal(rec: PlanRecord | null | undefined, tier: string, currentHash: string | null): LaunchRefusal | null {
  if (tier !== "heavy") return null;
  if (!rec || rec.status === "rejected") return "plan_required";
  if (rec.status !== "approved") return "checkpoint_pending";
  return currentHash === rec.hash ? null : "plan_changed";
}

// ---------------------------------------------------------------- reload survival (R41 item 17)
// A checkpoint approval and a plan-review verdict outlive /reload keyed by the plan VERSION hash (planVersionHash).
// Human approvals: <agentDir>/pi-foreman/state/approvals/<hash>.json, written only by this harness (never a model tool: the
// path is a policy floor) and never in round-state.json. No file from a parent (`ruling.md`, `ruling-plan.md`) approves a plan.

export const approvalsDir = (agentDir: string): string => path.join(agentDir, "pi-foreman", "state", "approvals");
const HASH_RE = /^[0-9a-f]{64}$/;

/** What the store keeps for one plan version. */
export interface StoredPlan {
  hash: string;
  topic: string;
  approval: { at: string; by: "user" | "rig" } | null;
  review: { verdict: Verdict; model: string | null; rounds: number; findings?: string[] } | null;
}

const storeFile = (agentDir: string, hash: string): string => path.join(approvalsDir(agentDir), `${hash}.json`);

/** The stored approval / review of a plan version, or null (no file, bad shape, a hash that is not the file's name). */
export function readStored(agentDir: string, hash: string): StoredPlan | null {
  if (!HASH_RE.test(hash)) return null;
  try {
    const st = fs.lstatSync(storeFile(agentDir, hash));
    if (!st.isFile() || st.size > 16 * 1024) return null;
    const v = JSON.parse(fs.readFileSync(storeFile(agentDir, hash), "utf8")) as Record<string, unknown>;
    if (!v || typeof v !== "object" || v.hash !== hash || typeof v.topic !== "string" || !/^[A-Za-z0-9._-]{1,64}$/.test(v.topic)) return null;
    const a = v.approval as Record<string, unknown> | null | undefined;
    const r = v.review as Record<string, unknown> | null | undefined;
    const approval = a && typeof a === "object" && typeof a.at === "string" && (a.by === "user" || a.by === "rig") ? { at: a.at, by: a.by as "user" | "rig" } : null;
    const review = r && typeof r === "object" && (r.verdict === "pass" || r.verdict === "fail") && (r.model === null || typeof r.model === "string") && typeof r.rounds === "number" && Number.isInteger(r.rounds) && r.rounds >= 1 ? { verdict: r.verdict as Verdict, model: r.model as string | null, rounds: r.rounds, ...(r.verdict === "fail" && Array.isArray(r.findings) ? { findings: r.findings.filter((x): x is string => typeof x === "string").slice(0, 40).map((x) => x.slice(0, 400)) } : {}) } : null;
    return { hash, topic: v.topic, approval, review };
  } catch {
    return null;
  }
}

/** Merge `patch` into the stored entry of a plan version (temp file + rename); a failure is not fatal and returns false. */
export function saveStored(agentDir: string, hash: string, topic: string, patch: { approval?: StoredPlan["approval"]; review?: StoredPlan["review"] }): boolean {
  if (!HASH_RE.test(hash)) return false;
  const dir = approvalsDir(agentDir);
  const file = storeFile(agentDir, hash);
  const tmp = `${file}.${process.pid}.tmp`;
  try {
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    if (fs.lstatSync(dir).isSymbolicLink()) return false;
    const old = readStored(agentDir, hash);
    const next: StoredPlan = { hash, topic, approval: patch.approval ?? old?.approval ?? null, review: patch.review ?? old?.review ?? null };
    fs.writeFileSync(tmp, JSON.stringify({ v: 1, ...next }) + "\n", { mode: 0o600 });
    fs.renameSync(tmp, file);
    return true;
  } catch {
    try {
      fs.rmSync(tmp, { force: true });
    } catch {
      // best effort
    }
    return false;
  }
}

/** The restorable state of the plan files now in the scratch dir: the newest stored human approval and every stored review. */
export interface StoredRestore {
  approved: { plan: PlanFile; at: string; by: "user" | "rig" } | null;
  reviews: { plan: PlanFile; review: NonNullable<StoredPlan["review"]> }[];
}

export function restoreFromStore(agentDir: string, o: PlanOpts): StoredRestore {
  const out: StoredRestore = { approved: null, reviews: [] };
  const scratch = scratchRoot(realDeep(path.resolve(workspaceOf(o.cwd).root)), o.scratchDir, o.platform);
  if (!scratch) return out;
  let names: string[];
  try {
    const all = fs.readdirSync(scratch).filter((n) => PLAN_NAME.test(n));
    names = all.filter((n) => !n.endsWith(".md") || !all.includes(`${n.slice(0, -3)}.html`)).sort(); // a page and its copy are one plan: the page
  } catch {
    return out;
  }
  for (const name of names) {
    const r = readPlan(path.join(scratch, name), o);
    if (!("plan" in r)) continue;
    const st = readStored(agentDir, r.plan.hash);
    if (!st) continue;
    if (st.review) out.reviews.push({ plan: r.plan, review: st.review });
    if (st.approval && (!out.approved || st.approval.at > out.approved.at)) out.approved = { plan: r.plan, ...st.approval };
  }
  return out;
}

/**
 * `ceremony.checkpoint`: the owner answers the checkpoint in the session's own pane, in every session. The old value `parent` is refused
 * with this text (no approval travels from a parent to a child); any other value, or none, is the owner's dialog. Null = no refusal.
 */
export function checkpointConfigRefusal(configured: unknown): string | null {
  return configured === "parent"
    ? `pi-foreman: ${CHECKPOINT_TOOL} refused [checkpoint_parent]: ceremony.checkpoint "parent" is no longer supported; no approval travels from a parent session to a child, the owner answers the checkpoint in this session's own pane. Remove ceremony.checkpoint from the user or overlay config (or set it to "human"), then call ${CHECKPOINT_TOOL} again.`
    : null;
}

/** The `foreman_checkpoint` refusal in a plan phase a parent's launch started, below heavy: the plan review ends that phase, not the owner. */
export function parentPhaseCheckpointText(triaged: boolean): string {
  const tier = triaged ? "" : ` Record your tier with foreman_triage first: without a recorded tier a plan-review PASS does not end the phase.`;
  return `pi-foreman: ${CHECKPOINT_TOOL} refused [plan_phase_review]: below tier heavy the plan phase your parent's launch started ends with your own plan review, not with a checkpoint: no builders until your plan review passes. Launch the reviewer with occasion: "plan-review" (or "[plan-review]" first in its task), naming the plan and the ledger; a PASS on the current version of the plan ends the phase.${tier}`;
}

/** The refusal text for a builder launch. `byReview`: a plan phase a parent's launch started, below heavy (it ends with the plan review's PASS). */
export function launchRefusalText(reason: LaunchRefusal, rec: PlanRecord | null | undefined, scratchDir: string, byReview = false): string {
  const head = `pi-foreman: builder launch refused [launch_refused:${reason}]:`;
  const name = rec ? `plan-${rec.topic}${rec.path.endsWith(".html") ? ".html" : ".md"}` : "";
  if (reason === "plan_phase" && byReview) return `${head} the session is in the plan phase: only explorers and plan-review reviewers launch, no builders until your plan review passes. Write the plan under ${scratchDir}/ (ask only for real decisions until it is decision-complete), then launch the reviewer with occasion: "plan-review" (or "[plan-review]" first in its task) on it; a PASS on the current version ends the phase. The owner can also end it with /foreman plan off.`;
  if (reason === "plan_phase") return `${head} the session is in the plan phase: only explorers and plan-review reviewers launch. Write the plan under ${scratchDir}/ (ask only for real decisions until it is decision-complete), then call ${CHECKPOINT_TOOL}; an approval ends the phase. The owner can also end it with /foreman plan off.`;
  if (reason === "plan_required" && rec?.status === "rejected") return `${head} the owner rejected ${name}, so the heavy path is stopped. Launch no builder; report to the owner and ask how to go on. A new plan needs a new ${CHECKPOINT_TOOL} approval.`;
  if (reason === "plan_required") return `${head} at tier heavy a builder starts only after the owner approved a plan. Write ${scratchDir}/plan-<topic>.html (a page) or plan-<topic>.md, then call ${CHECKPOINT_TOOL} with its path and wait for the owner's answer.`;
  if (reason === "checkpoint_pending") return `${head} the checkpoint of ${name} is ${rec?.status === "revise" ? "waiting for a revised plan" : "pending (no answer from the owner yet)"}. ${rec?.status === "revise" ? `Change the plan as the owner asked, then call ${CHECKPOINT_TOOL} again.` : `Ask the owner in your reply, or call ${CHECKPOINT_TOOL} again with the same path.`}`;
  return `${head} ${name} changed or is gone since the owner approved it. Call ${CHECKPOINT_TOOL} again so the owner approves the current version.`;
}

export const clean = (s: string): string => s.replace(/\x1b\[[0-9;?]*[ -/]*[@-~]/g, "").replace(/[\u0000-\u001f\u007f\u0080-\u009f]/g, " ").trim().slice(0, 200);

/** The title of a plan: its first column-0 `#` heading, else its topic (the `<topic>` of `plan-<topic>.md`), else null (callers pick their own fallback). */
export function planTitle(lines: readonly string[], topic: string | null): string | null {
  const h = lines.map((l) => topHeading(l)).find((x) => x?.level === 1 && x.text);
  return h?.text ?? topic ?? null;
}

/** What the owner sees before the dialog: title, goal lines, section headings, path, hash prefix (at most 12 lines). */
export function planSummary(text: string, rel: string, hash: string): string {
  const all = text.split(/\r?\n/);
  const cut = all.findIndex(isAppendixLine);
  const lines = cut < 0 ? all : all.slice(0, cut);
  const heads = lines.map((l) => topHeading(l));
  const topic = PLAN_NAME.exec(path.basename(rel))?.[1] ?? null;
  const title = planTitle(lines, topic) ?? lines.find((l) => l.trim() && !l.startsWith("<!--") && !topHeading(l)) ?? "(untitled)";
  const sections = heads.filter((h): h is { level: number; text: string } => !!h && h.level > 1).map((h) => clean(h.text));
  const goal: string[] = (goalParagraph(ownerSectionOf(lines)?.lines ?? []) ?? []).map(clean);
  const goalAt = goal.length ? -1 : heads.findIndex((h) => !!h && /^goal\b/i.test(h.text));
  if (goalAt >= 0) {
    for (const l of lines.slice(goalAt + 1)) {
      if (topHeading(l)) break;
      if (l.trim()) goal.push(clean(l));
      if (goal.length === 4) break;
    }
  }
  const openAt = heads.findIndex((h) => !!h && /^open questions\b/i.test(h.text));
  let open = 0;
  if (openAt >= 0) {
    for (const l of lines.slice(openAt + 1)) {
      if (topHeading(l)) break;
      if (l.trim()) open++;
    }
  }
  const out = [`Plan: ${clean(title)}`, ...goal.map((g, i) => (i === 0 ? `Goal: ${g}` : `  ${g}`)), `Sections: ${sections.join(" · ").slice(0, 200) || "(none)"}`, ...(open > 0 ? [`Open questions: ${open}`] : []), ...(cut < 0 ? [] : [`Appendix: from "${clean(all[cut])}" (outside review and approval)`]), `File: ${rel}`, `sha256: ${hash.slice(0, 12)}`];
  return out.slice(0, 12).join("\n");
}
