export const PLAN_NAME = /^plan-([A-Za-z0-9._-]{1,64})\.(md|html)$/;
/** The rulings sidecar of an HTML plan: outside PLAN_NAME, so it is never taken for a plan. */
export const RULINGS_NAME = /^rulings-([A-Za-z0-9._-]{1,64})\.md$/;
export const generatedMarker = (topic: string): string => `<!-- generated by pi-foreman from plan-${topic}.html: edit the page, not this copy -->`;
// approve last: never the preselected option, so a stray Enter does not approve.
